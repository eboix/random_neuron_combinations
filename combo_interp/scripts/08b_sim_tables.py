#!/usr/bin/env python3
"""CPU: simulator scores only (no writer / probe results needed), and LaTeX tables of them by condition and layer.
Needs private/ (true activations, unit conditions), so it runs where private/ is (cluster: slurm/submit.sh score_sim).

  python scripts/08b_sim_tables.py --config ...   # -> scores/<tag>/<threshold>/unit_scores.csv, results/<tag>/sim_tables.tex
The full `08_score_and_analyze.py` (after probe) rewrites unit_scores.csv with the writer's metrics added.
"""
from _common import setup

cfg, paths, args = setup(__doc__)
from combo_interp.scoring import compute_scores  # noqa: E402
from combo_interp.tables import sim_tables  # noqa: E402

df = compute_scores(cfg, paths, [])
df = df[df["sim_spearman"].notna()]
out = paths.agent_analysis / "sim_tables.tex"
out.parent.mkdir(parents=True, exist_ok=True)
tex = (f"% {cfg.model.name}, {len(df)} units with simulator results"
       f"{', agent run ' + paths.run_tag if paths.run_tag else ''}. Generated by scripts/08b_sim_tables.py.\n"
       "% Needs \\usepackage{booktabs}.\n\n" + sim_tables(df, cfg))
out.write_text(tex)
print(tex)
print(f"[sim-tables] {len(df)} units -> {out}")
